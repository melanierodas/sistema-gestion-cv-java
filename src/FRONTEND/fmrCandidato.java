    public void mostrarCandidatosEnTabla(){
    String[] titulos = {"Correo", "Nombre", "Teléfono", "Dirección"};
    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(null, titulos);
    
    clsCandidato backend = new clsCandidato();
    java.util.ArrayList<clsCandidato> lista = backend.fncListarTodos();
    
    Object[] fila = new Object[4];
    for(clsCandidato c : lista){
        fila[0] = c.getCorreo();
        fila[1] = c.getNombre();
        fila[2] = c.getTelefono();
        fila[3] = c.getDireccion();

        modelo.addRow(fila);
    }
    tblCandidatos.setModel(modelo);
}
