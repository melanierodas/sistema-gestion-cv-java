    public void Limpiar(){
        txtCorreo.setText(""); 
        txtNombre.setText("");
        txtTelefono.setText(""); 
        txtDireccion.setText(""); 
        txtFoto.setText(""); 
        txtPerfil.setText(""); 
    }
    
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if(txtCorreo.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "El Correo es Obligatorio");
            return; 
        }
       
        clsCandidato verificador = new clsCandidato();
        verificador = verificador.fncBuscar(txtCorreo.getText());

        if(verificador == null) {
            clsCandidato candidato = new clsCandidato(); 
            candidato.setCorreo(txtCorreo.getText()); 
            candidato.setNombre(txtNombre.getText()); 
            candidato.setTelefono(txtTelefono.getText()); 
            candidato.setDireccion(txtDireccion.getText()); 
            candidato.setFoto(txtFoto.getText()); 
            candidato.setPerfil(txtPerfil.getText()); 

            candidato.fncIngresar(candidato); 
        }

        JOptionPane.showMessageDialog(this, "Currículum Completo Registrado con Éxito");

        Limpiar(); 
        mostrarCandidatosEnTabla();
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        if(txtCorreo.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Ingrese un correo");
            return;
        }
        
        clsCandidato candidato = new clsCandidato(); 
        candidato = candidato.fncBuscar(txtCorreo.getText()); 
        if(candidato !=null){
            txtNombre.setText(candidato.getNombre()); 
            txtTelefono.setText(candidato.getTelefono());
            txtDireccion.setText(candidato.getDireccion());
            txtFoto.setText(candidato.getFoto());
            txtPerfil.setText(candidato.getPerfil()); 
        }else{
            JOptionPane.showMessageDialog(this, "Candidato no Encontrado"); 
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        clsCandidato candidato = new clsCandidato(); 
        candidato.setCorreo(txtCorreo.getText()); 
        candidato.setNombre(txtNombre.getText()); 
        candidato.setTelefono(txtTelefono.getText()); 
        candidato.setDireccion(txtDireccion.getText()); 
        candidato.setFoto(txtFoto.getText()); 
        candidato.setPerfil(txtPerfil.getText()); 
        int Resp = candidato.fncModificar(candidato); 
        
        if(Resp==1){
            JOptionPane.showMessageDialog(this, "Modificado Correctamente"); 
            mostrarCandidatosEnTabla();
            Limpiar();
            
        }else{
            JOptionPane.showMessageDialog(this, "Error al Modificar"); 

        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int Resp = new clsCandidato().fncEliminar(txtCorreo.getText()); 
        if(Resp == 1){
            JOptionPane.showMessageDialog(this, "Eliminado Correctamente");
            Limpiar(); 
            mostrarCandidatosEnTabla();
            
        }else{
            JOptionPane.showMessageDialog(this, "Error al Eliminar"); 

        }
    }//GEN-LAST:event_btnEliminarActionPerformed

