    private void btnGuardarEstudioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarEstudioActionPerformed
        if(txtInstitucion.getText().isEmpty() || txtTitulo.getText().isEmpty() || txtFechaInicio.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Institución, Título y Fecha de Inicio son obligatorios");
            return; 
        }
        
        clsEstudios estudio = new clsEstudios(); 
        System.out.println(correoCandidatoDestino);
        estudio.setCorreoCandidato(this.correoCandidatoDestino); 
        estudio.setInstitucion(txtInstitucion.getText());
        estudio.setTitulo(txtTitulo.getText());
        estudio.setDescripcion(txtDescripcion.getText());
        estudio.setFechaInicio(txtFechaInicio.getText());
        estudio.setFechaFinal(txtFechaFinal.getText());

        int respuesta = estudio.fncIngresar(estudio);
        if(respuesta == 1){
    JOptionPane.showMessageDialog(this, "Estudio académico registrado con éxito");
    Limpiar();
    mostrarEstudiosEnTabla();
}else{
            JOptionPane.showMessageDialog(this, "Error al registrar el estudio");
        }
    }//GEN-LAST:event_btnGuardarEstudioActionPerformed

    private void btnModificarEstudioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarEstudioActionPerformed
        if (idEstudioSeleccionado == 0) {
        JOptionPane.showMessageDialog(this, "Debe dar doble clic sobre un estudio de la tabla para modificarlo");
        return;
    }

    if(txtInstitucion.getText().isEmpty() || txtTitulo.getText().isEmpty() || txtFechaInicio.getText().isEmpty()){
        JOptionPane.showMessageDialog(this, "Institución, Título y Fecha de Inicio son obligatorios");
        return; 
    }

    clsEstudios estudio = new clsEstudios();

    estudio.setIdEstudio(idEstudioSeleccionado);
    estudio.setInstitucion(txtInstitucion.getText());
    estudio.setTitulo(txtTitulo.getText());
    estudio.setDescripcion(txtDescripcion.getText());
    estudio.setFechaInicio(txtFechaInicio.getText());
    estudio.setFechaFinal(txtFechaFinal.getText());

    int resp = estudio.fncModificar(estudio);

    if(resp == 1){
        JOptionPane.showMessageDialog(this, "Estudio modificado correctamente");
        Limpiar();
        mostrarEstudiosEnTabla();
        idEstudioSeleccionado = 0;
    }else{
        JOptionPane.showMessageDialog(this, "Error al modificar el estudio");
    }
    }//GEN-LAST:event_btnModificarEstudioActionPerformed

