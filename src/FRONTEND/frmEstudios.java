    private void tlbEstudiosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tlbEstudiosMouseClicked
        if (evt.getClickCount() == 2) {
        int fila = tlbEstudios.getSelectedRow();

        if (fila >= 0) {
            idEstudioSeleccionado = Integer.parseInt(tlbEstudios.getValueAt(fila, 0).toString());

            txtInstitucion.setText(tlbEstudios.getValueAt(fila, 1).toString());
            txtTitulo.setText(tlbEstudios.getValueAt(fila, 2).toString());
            txtFechaInicio.setText(tlbEstudios.getValueAt(fila, 3).toString());

            Object fechaFinal = tlbEstudios.getValueAt(fila, 4);
            txtFechaFinal.setText(fechaFinal == null ? "" : fechaFinal.toString());

            Object descripcion = tlbEstudios.getValueAt(fila, 5);
            txtDescripcion.setText(descripcion == null ? "" : descripcion.toString());
        }
    }
    }//GEN-LAST:event_tlbEstudiosMouseClicked
public void mostrarEstudiosEnTabla() {
    String[] titulos = {"ID", "Institución", "Título", "Fecha Inicio", "Fecha Final", "Descripción"};

    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(null, titulos) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    clsEstudios backend = new clsEstudios();
    java.util.ArrayList<clsEstudios> lista = backend.fncListarPorCandidato(this.correoCandidatoDestino);

    Object[] fila = new Object[6];

    for (clsEstudios e : lista) {
        fila[0] = e.getIdEstudio();
        fila[1] = e.getInstitucion();
        fila[2] = e.getTitulo();
        fila[3] = e.getFechaInicio();
        fila[4] = e.getFechaFinal();
        fila[5] = e.getDescripcion();

        modelo.addRow(fila);
    }

    tlbEstudios.setModel(modelo);

    tlbEstudios.setRowSelectionAllowed(true);
    tlbEstudios.setColumnSelectionAllowed(false);
    tlbEstudios.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
}
