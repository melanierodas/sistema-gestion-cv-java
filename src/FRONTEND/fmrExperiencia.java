    private void tblExperienciaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblExperienciaMouseClicked
        if (evt.getClickCount() == 2) {
        int fila = tblExperiencia.getSelectedRow();

        if (fila >= 0) {
            idExperienciaSeleccionada = Integer.parseInt(tblExperiencia.getValueAt(fila, 0).toString());

            txtEmpresa.setText(tblExperiencia.getValueAt(fila, 1).toString());
            txtPuesto.setText(tblExperiencia.getValueAt(fila, 2).toString());
            txtFechaInicio.setText(tblExperiencia.getValueAt(fila, 3).toString());

            Object fechaFinal = tblExperiencia.getValueAt(fila, 4);
            txtFechaFinal.setText(fechaFinal == null ? "" : fechaFinal.toString());

            Object funciones = tblExperiencia.getValueAt(fila, 5);
            txtFunciones.setText(funciones == null ? "" : funciones.toString());
        }
    }
    }//GEN-LAST:event_tblExperienciaMouseClicked
    
    
    public void mostrarExperienciasEnTabla(){
    String[] titulos = {"ID", "Empresa", "Puesto", "Fecha Inicial", "Fecha Final", "Funciones"};

    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(null, titulos) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };
    
    clsExperiencia backend = new clsExperiencia();
    java.util.ArrayList<clsExperiencia> lista = backend.fncListarPorCorreo(this.correoCandidatoDestino);
    
    Object[] fila = new Object[6];

    for(clsExperiencia c : lista){
        fila[0] = c.getIdExperiencia();
        fila[1] = c.getEmpresa();
        fila[2] = c.getPuesto();
        fila[3] = c.getFechaInicio();
        fila[4] = c.getFechaFinal();
        fila[5] = c.getFunciones();

        modelo.addRow(fila);
    }

    tblExperiencia.setModel(modelo);

    // Esto evita que la tabla entre en modo edición
    // y permite seleccionar una fila completa
    tblExperiencia.setRowSelectionAllowed(true);
    tblExperiencia.setColumnSelectionAllowed(false);
    tblExperiencia.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
}
